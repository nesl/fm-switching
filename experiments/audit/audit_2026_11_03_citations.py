#!/usr/bin/env python3
"""Append the citation survey to reports/audit_2026_11_03.md.

Lists files in the WRITTEN RECORD (reports/, results/INDEX.md, research/, plots/) that cite an
affected study, excluding the study's own report/script (a self-reference is not a citation) and
excluding the files this audit edited. These files are listed, NOT edited.
"""
import re, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EDITED = {
 "CLAUDE.md", "research/EXPERIMENTS.md", "research/STATUS.md", "research/DECISIONS.md",
 "research/FORMULATION.md", "research/CLAIMS.md", "research/KILL_CONDITIONS.md",
 "reports/audit_2026_11_03.md",
} | {f"reports/{x}" for x in [
 "study_r1_cloud32b_sember.md", "device_tier_accuracy_llamacpp.md",
 "study_rh3_warmable_representations.md", "study_rh4_fixed_stride.md",
 "study_o_q4_separating_cell.md", "r4_device_signals_prep.md",
 "study_rh7_eager_vs_lazy.md", "study_rh8_demand_aware_warm_state.md",
 "device_fast_path.md", "device_runtime_probe.md", "study_m_smoke_toff.md"]}

# (label, regex, self-reference substrings to drop)
GROUPS = [
 ("E24 / E24b / E24c — INVALID", r"\bE24[bc]?\b",
  ["e24_", "e24b_", "e24c_", "sweep_e24c", "plot_e24", "simulator/"]),
 ("StudyI2 SPATIAL + TEMPORAL — INVALID", r"\bStudy ?I2\b", ["study_i2"]),
 ("StudyI3 TEMPORAL + reanalysis — INVALID", r"\bStudy ?I3\b", ["study_i3"]),
 ("StudyI DENSE arm — same window defect", r"\bStudy ?I\b(?![0-9-])", ["study_i_", "study_i/"]),
 ("StudyD / StudyD2 — INVALID", r"\bStudy ?D2?\b(?![0-9])", ["study_d_", "study_d2"]),
 ("StudyJ as a gate — INVALID", r"\bStudy ?J\b(?![0-9-])", ["study_j_", "study_j."]),
 ("CONFOUNDED Thinking arms (K, J2, J3, J5, J6, P, Q, S1, S2, T, R4-prep, StudyO 4B-T)",
  r"\bStudy ?(K|J2|J3|J5|J6|P|Q|S1|S2|T|R4-prep|O)\b",
  ["study_k", "study_j2", "study_j3", "study_j5", "study_j6", "study_p", "study_q",
   "study_s1", "study_s2", "study_t", "r4_device_signals", "study_o"]),
]
files = subprocess.run(["git", "ls-files"], capture_output=True, text=True, cwd=ROOT).stdout.split()
keep = [f for f in files
        if f not in EDITED
        and (f.startswith(("reports/", "research/", "plots/")) or f == "results/INDEX.md")
        and f.endswith((".md", ".py"))]

L = ["", "---", "", "## Files citing these results as findings (listed, NOT edited)", "",
     "Cross-references only: a study's own report or script is excluded, as is every file this "
     "audit edited. Generated by `experiments/audit/audit_2026_11_03_citations.py`.", ""]
for label, pat, selfref in GROUPS:
    byf = {}
    for f in keep:
        if any(s in f for s in selfref):
            continue
        try:
            txt = (ROOT / f).read_text(errors="replace").split("\n")
        except Exception:
            continue
        for i, line in enumerate(txt, 1):
            if re.search(pat, line):
                byf.setdefault(f, []).append(i)
    n = sum(len(v) for v in byf.values())
    L.append(f"**{label}** — {n} line(s) in {len(byf)} file(s)")
    L.append("")
    if not byf:
        L.append("- none")
    for f in sorted(byf):
        ln = ", ".join(str(i) for i in byf[f])
        L.append(f"- `{f}`: {ln}")
    L.append("")
out = ROOT / "reports/audit_2026_11_03.md"
s = out.read_text()
marker = "## Files citing these results as findings"
assert marker not in s, "citation section already present"
out.write_text(s.rstrip("\n") + "\n" + "\n".join(L) + "\n")
print(f"appended citation survey ({len(L)} lines) to {out}")
