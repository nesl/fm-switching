w()

# ============================================================ 8
SB = R["side_by_side"]["cells"]
SCH = R["side_by_side"]["streaming_chance"]
w("## 8. Side by side with StudyE9b's streaming AP — where the two metrics agree and where they differ")
w()
w("> " + R["side_by_side"]["note"])
w()
w("| arm | " + " | ".join(f"challenge h = {x}" for x in HS) + " | challenge mAP | "
  + " | ".join(f"streaming h = {x}" for x in HS) + " |")
w("|---|---|---|---|---|---|---|---|")
for k, v in SB.items():
    w(f"| {k.replace('|', ', ').replace('BI_N', 'B N = ')} | "
      + " | ".join(f"{v['challenge'][h]:.4f}" for h in H)
      + f" | **{v['challenge_mAP']:.4f}** | "
      + " | ".join(f"{v['streaming'][h]:.4f}" for h in H) + " |")
w()
w("### 8.1 What transfers between the two metrics, and what does not")
w()
w("A level comparison is meaningless — the chance rates differ by a factor of "
  f"{MEANBR / SCH:.0f}. The comparable quantity is **how far above chance an arm sits, as a "
  f"multiple of how far above chance the reference arm sits**. That ratio is dimensionless and "
  f"can be compared across metrics:")
w()
w("| contrast at h = 0.5 s | challenge: excess over chance | streaming: excess over chance | "
  "challenge ratio | streaming ratio |")
w("|---|---|---|---|---|")
h0 = H[0]


def exc(key, metric):
    v = SB[key]
    return (v["challenge"][h0] - BR[h0]) if metric == "c" else (v["streaming"][h0] - SCH)


rows = [("32BI_N1|zero", "4BI_N1|zero", "32B N = 1 vs 4B N = 1, zero latency"),
        ("always-cloud 32BI_N1|measured@25", "device-only 4BI_N1|measured@25",
         "always-cloud 32B N = 1 vs device-only, (ii) @25 %"),
        ("always-cloud 32BI_N3|measured@25", "always-cloud 32BI_N1|measured@25",
         "always-cloud 32B N = 3 vs 32B N = 1, (ii) @25 %"),
        ("always-cloud 32BI_N1|measured@75", "device-only 4BI_N1|measured@75",
         "always-cloud 32B N = 1 vs device-only, (ii) @75 %")]
ratios = []
for a, b, lbl in rows:
    ca, cb = exc(a, "c"), exc(b, "c")
    sa, sb_ = exc(a, "s"), exc(b, "s")
    rc, rs = ca / cb, sa / sb_
    ratios.append((lbl, rc, rs))
    agree = abs(rc - rs) / max(rs, 1e-9) <= 0.35
    w(f"| {lbl} | {ca:+.4f} vs {cb:+.4f} | {sa:+.4f} vs {sb_:+.4f} | **{rc:.2f}x** | "
      f"**{rs:.2f}x**{'' if agree else ' — **2x apart**'} |")
w()
close = [r for r in ratios if abs(r[1] - r[2]) / max(r[2], 1e-9) <= 0.35]
far = [r for r in ratios if r not in close]
w(f"**Sign and ordering transfer in every one of these contrasts. Magnitude (the "
  f"excess-over-chance ratio) transfers to within 35 % in {len(close)} of {len(ratios)} and not "
  f"in {len(far)}** — so the honest summary is *not* \"the two metrics agree\".")
w()
w(f"The {len(close)} that agree ("
  + "; ".join(f"{lbl}: {rc:.2f}x vs {rs:.2f}x" for lbl, rc, rs in close)
  + f") are the contrasts where **both arms sit near chance** on both scales. The one that does "
    f"not (" + "; ".join(f"{lbl}: {rc:.2f}x vs {rs:.2f}x" for lbl, rc, rs in far)
  + f") is the contrast where **the challenge metric is near its ceiling**: with 150 balanced "
    f"negatives, 4B N = 1 already reaches {SB['4BI_N1|zero']['challenge'][h0]:.3f} at h = 0.5 s, "
    f"so there is little room above it and the ratio compresses toward 1. The streaming metric, "
    f"with a {1/SCH:.0f}:1 negative set, has no such ceiling.")
w()
w("**The usable rule, and the central result of the study:** *signs and orderings transfer "
  "between the two metrics unconditionally; excess-over-chance ratios transfer only while both "
  "arms are near chance; absolute AP levels never transfer.* The project's streaming AP has not "
  "been measuring something other than the challenge — it has been measuring the same orderings "
  f"on a scale whose chance floor is {MEANBR / SCH:.0f}x lower and whose ceiling is far away. "
  "Claims phrased as a sign or an ordering survive translation; claims phrased as a multiple need "
  "the near-chance caveat; claims phrased as an absolute AP do not transfer at all.")
w()
w("### 8.2 Where they agree")
w()
p = R["paired"]
w(f"1. **32B beats 4B at zero latency**, with a CI excluding 0 under both metrics: challenge mAP "
  f"{p['32BI_N1 - 4BI_N1|zero']['mAP']['diff']:+.4f} "
  f"[{p['32BI_N1 - 4BI_N1|zero']['mAP']['ci'][0]:+.4f}, "
  f"{p['32BI_N1 - 4BI_N1|zero']['mAP']['ci'][1]:+.4f}]; StudyE5 Part G and StudyE9b report the "
  f"same sign at these horizons.")
w(f"2. **The delivered cloud beats the delivered device**: challenge mAP "
  f"{p['always-cloud 32BI_N1 - device-only|measured@25']['mAP']['diff']:+.4f} "
  f"[{p['always-cloud 32BI_N1 - device-only|measured@25']['mAP']['ci'][0]:+.4f}, "
  f"{p['always-cloud 32BI_N1 - device-only|measured@25']['mAP']['ci'][1]:+.4f}] at 25 % load, "
  f"{p['always-cloud 32BI_N1 - device-only|measured@75']['mAP']['diff']:+.4f} "
  f"[{p['always-cloud 32BI_N1 - device-only|measured@75']['mAP']['ci'][0]:+.4f}, "
  f"{p['always-cloud 32BI_N1 - device-only|measured@75']['mAP']['ci'][1]:+.4f}] at 75 %. Same "
  f"sign, same load ordering, as StudyE9b.")
w(f"3. **Server load costs the cloud some of its advantage**, through the hold shift alone, under "
  f"both metrics.")
w(f"4. **Escalation buys nothing at these horizons.** Challenge mAP against device-only: "
  f"{p['escalation trig10 - device-only|measured@25']['mAP']['diff']:+.4f} at trigger 10 % and "
  f"{p['escalation trig20 - device-only|measured@25']['mAP']['diff']:+.4f} at 20 %, **neither CI "
  f"excluding 0**. StudyE9b reached the same conclusion from the other direction (its finding 7: "
  f"the gate, not the resolver, is binding).")
w()
w("### 8.3 Where they differ — and this one matters")
w()
n3c = SB["always-cloud 32BI_N3|measured@25"]
n1c = SB["always-cloud 32BI_N1|measured@25"]
w(f"**StudyE9b's finding 2 — \"32B N = 3 falls *below* N = 1 once delivered\" — is a statement "
  f"about h = 0 and h = 0.25 s, and it does not survive at the challenge's horizons.**")
w()
w("| metric | 32B N = 3 | 32B N = 1 | N = 3 as a share of N = 1's excess over chance |")
w("|---|---|---|---|")
w(f"| StudyE9b streaming, h = 0 | {S1['baselines']['always-cloud/32BI_N3|measured@25|cad50|far5']['ap']['0.0']['ap']:.4f} "
  f"| {S1['baselines']['always-cloud/32BI_N1|measured@25|cad50|far5']['ap']['0.0']['ap']:.4f} | "
  f"**{(S1['baselines']['always-cloud/32BI_N3|measured@25|cad50|far5']['ap']['0.0']['ap'] - SCH) / (S1['baselines']['always-cloud/32BI_N1|measured@25|cad50|far5']['ap']['0.0']['ap'] - SCH):.0%}** |")
