#!/usr/bin/env python3
"""A REAL TRACE SLICE for the all-arm tests. D205 (3). CPU only, no server, no measurement.

WHY THIS EXISTS. The all-arm legality and fairness tests used to run every registered arm on a
SYNTHETIC trace, whose instants are invented and therefore carry no committed device score. Once
the device score is a real decision input, those tests cannot assert anything about an arm that
reads one: the arm correctly raises. The remedy D205 (3) ruled is this module. The events here are
built from a REAL trace generated by `fleet/trace.py`, from a DEVELOPMENT SEED, and every monitor
instant carries the StudyORIN1 score the generator itself put in `device_answers`.

SEEDS. Development seeds only, and the default is 0. Seeds 1 to 3 are RESERVED FOR ROUND 1
(`policy/audit/_harness.py`) and there is no HOLDOUT seed here; `seed()` refuses anything else
rather than trusting a caller.

WHAT IT IS NOT. A slice of a few seconds of two devices is not a cell and nothing computed from it
is a measurement. It exists so that "every registered arm emits only legal actions" can be asserted
against instants that are real.
"""
from __future__ import annotations

import sys
from pathlib import Path
from typing import Any, Dict, List

HERE = Path(__file__).resolve().parent
LIVE2 = HERE.parent
for _p in (str(LIVE2), str(LIVE2 / "fleet")):
    if _p not in sys.path:
        sys.path.insert(0, _p)

import links as LK                                                     # noqa: E402
import schema as SC                                                    # noqa: E402
import trace as TR                                                     # noqa: E402
import traces as T                                                     # noqa: E402

DEV_SEEDS = (0, 4, 5, 6)
RESERVED_SEEDS = (1, 2, 3)


def check_seed(seed: int) -> int:
    if int(seed) in RESERVED_SEEDS:
        raise ValueError(
            "seed %d is RESERVED FOR ROUND 1 and may not be used for a test slice (D205 (3))"
            % seed)
    if int(seed) not in DEV_SEEDS:
        raise ValueError("seed %d is not a development seed %s (D205 (3))" % (seed, list(DEV_SEEDS)))
    return int(seed)


def real_slice(*, seed: int = 0, n_devices: int = 4, duration_s: float = 300.0,
               ratio: str = "50:50", upload_mode: str = "A") -> Dict[str, Any]:
    """Wire events for a real trace slice, in the same shape `traces.synthetic` returns.

    The conversion is mechanical and derives nothing: each trace record becomes the wire event the
    emulator would send for it, with the same fields, and the monitor events carry the generator's
    own `device_score` for that instant. `t_arrive` is the capture time plus this module's own
    `upload_s`, which is what the SYNTHETIC builder did too; a slice is not a timing model.
    """
    check_seed(seed)
    # 4 devices over 300 s, not 2 over 120 s. The smaller slice carried ONE recall question, and
    # `device-only` never offloads a monitor instant, so it emitted zero decisions and zero
    # requests and the all-arm legality assertion could not say anything about it. A slice that
    # cannot exercise an arm is not a cell that arm passed: this is the port rule applied to the
    # fixture. `n_recall_questions` is returned so a future shrink is caught by the test and not
    # by a silent zero.
    b = TR.generate_trace(int(seed), int(n_devices), ratio, float(duration_s), upload_mode)
    score_of = {str(a["opportunity_id"]): a.get("device_score")
                for a in b["device_answers"] if a.get("kind") == "monitor"}
    missing = [k for k, v in score_of.items() if v is None]
    if missing:
        raise RuntimeError(
            "a REAL trace slice carried %d monitor instants with no committed device score, which "
            "cannot happen: fleet/trace.py refuses an instant the committed StudyORIN1 set does "
            "not cover. First: %r" % (len(missing), missing[0]))
    ev: List[Dict[str, Any]] = []
    frames_by_instant: Dict[str, str] = {}
    for r in b["records"]:
        k = r["kind"]
        if k == "device_register":
            # The real trace leaves the link fields None on purpose: the fleet assigns links
            # separately (`fleet/links.py`), and the emulator fills them from LinkSpec. A slice
            # has no emulator, so the SAME committed defaults are read from the same place rather
            # than typed in here. They are uniform in round 1 (links.py: 13.6 Mbit/s, 44 ms,
            # fixed, no variability and no outages), so this is a read and not a choice.
            _spec = LK.LinkSpec()
            ev.append(SC.make("device_register", device_id=r["device_id"], type=r["type"],
                              uplink_mbps=float(r["uplink_mbps"] if r["uplink_mbps"] is not None
                                                else _spec.uplink_mbps),
                              rtt_ms=float(r["rtt_ms"] if r["rtt_ms"] is not None
                                           else _spec.rtt_ms),
                              start_t=r["start_t"]))
        elif k in ("session_start", "session_end"):
            ev.append(SC.make(k, device_id=r["device_id"], session_id=r["session_id"], t=r["t"]))
        elif k == "history_preload":
            ev.append(SC.make("history_preload", device_id=r["device_id"],
                              session_id=r["session_id"], frame_refs=list(r["frame_refs"]),
                              est_tokens=int(r["est_tokens"]), t=r["t"]))
        elif k == "history_batch":
            ev.append(SC.make("history_append", device_id=r["device_id"],
                              session_id=r["session_id"], batch_id=r["batch_id"],
                              t_arrive=round(float(r["t"]) + T.upload_s(
                                  int(r.get("frame_bytes") or 0) or 1), 4),
                              frame_refs=list(r["frame_refs"]), est_tokens=int(r["est_tokens"])))
        elif k == "monitor_opportunity":
            opp = str(r["opportunity_id"])
            frames_by_instant[opp] = r["frame_ref"]
            nb = int(r["frame_bytes"])
            kw = dict(device_id=r["device_id"], opportunity_id=opp, instant_id=opp,
                      t_capture=r["t"], deadline_s=r["deadline_s"],
                      device_score=score_of[opp])
            if upload_mode == "B":
                ev.append(SC.make("monitor_offer", frame_bytes=nb, **kw))
            else:
                epi = {f: r[f] for f in ("episode_id", "episode_index", "frame_refs",
                                         "episode_frames") if f in r}
                ev.append(SC.make("monitor_frame", t_arrive=round(float(r["t"])
                                                                  + T.upload_s(nb), 4),
                                  frame_ref=r["frame_ref"], frame_bytes=nb, **epi, **kw))
        elif k == "recall_question":
            ev.append(SC.make("recall_question", device_id=r["device_id"],
                              opportunity_id=r["opportunity_id"], session_id=r["session_id"],
                              question_id=r["question_id"], t_ask=r["t"],
                              t_arrive=round(float(r["t"]) + T.upload_s(1), 4),
                              deadline_s=r["deadline_s"], question=r.get("question"),
                              options=list(r.get("options") or []), category=r.get("category")))
    ev.sort(key=T._sched)
    return dict(label="REAL-SLICE", events=ev, ratio=ratio, seed=int(seed),
                fairness_digest=T.fairness_digest(ev, upload_mode),
                live1_trace_digest=T.live1_trace_digest(ev),
                frames_by_instant=frames_by_instant, upload_mode=upload_mode,
                duration_s=float(duration_s), n_devices=int(n_devices),
                device_score_fixture=False,
                n_monitor_instants=len(score_of),
                n_recall_questions=sum(1 for e in ev if e["kind"] == "recall_question"),
                note=("A REAL TRACE SLICE from development seed %d, %d devices, %.0f s. Every "
                      "monitor instant carries the committed StudyORIN1 device score that "
                      "fleet/trace.py put in device_answers. IT IS NOT A CELL AND NOTHING "
                      "COMPUTED FROM IT IS A MEASUREMENT." % (seed, n_devices, duration_s)))
