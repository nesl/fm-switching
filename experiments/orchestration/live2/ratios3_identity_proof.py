#!/usr/bin/env python3
"""EVAL_PLAN composition conditions: proof that adding the ratio keys "10:4:2" and "3:11:2" to
`live2/fleet/trace.py` RATIOS_3 leaves every existing trace byte-identical.

One sha, two trees: the PRISTINE module is `git show HEAD:experiments/orchestration/live2/fleet/trace.py`
(passed in as a file), the PATCHED module is the working tree. Both are loaded under distinct module names
with every sibling import resolving to the same working-tree files, so the only difference is the patch.
Each generates the committed frozen-grid trace (seed 4, 16 devices, 1200 s, mode A, 40:40:20, lh_req, ss2,
EP-G with min 3 frames, per-frame robot upload, re-ask mean 30 s: the harness's own arguments for
`seed4_n16_1200s_A_r40-40-20_lh_req_ss2_L3_epg_perframe_rq30`) and the digests are compared with each other
and with the committed trace on disk. The two new keys are then generated by the patched module and their
fleet split recorded. CPU only; one process; run under experiments/orchestration/proof_guard.sh.
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
for _p in (str(HERE), str(HERE / "fleet"), str(HERE / "scorer"), str(HERE / "hybrid"),
           str(REPO / "experiments/orchestration/live"), str(REPO / "experiments/orchestration/baselines"),
           str(REPO / "experiments/orchestration/sim"), str(REPO / "experiments/lib")):
    if _p not in sys.path:
        sys.path.insert(0, _p)

KW = dict(robot_question_set="lh_req", ss_question_set="ss2", dashcam_format="epg", dashcam_min_frames=3,
          robot_upload="per-frame", robot_reask_mean_s=30.0)
MANIFEST = Path.home() / "data/live2/jpeg/combined_manifest.jsonl"   # the driver passes it (frame_bytes_source)
COMMITTED = Path.home() / "data/live2/frozen_grid/work/traces/seed4_n16_1200s_A_r40-40-20_lh_req_ss2_L3_epg_perframe_rq30"


def load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, str(path))
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod                     # dataclasses resolve their module through sys.modules
    spec.loader.exec_module(mod)
    return mod


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def gen(mod, out: Path, ratio: str) -> dict:
    t0 = time.time()
    meta = mod.write_trace(out, mod.generate_trace(4, 16, ratio, 1200.0, "A", frame_manifest=MANIFEST, **KW))
    return dict(ratio=ratio, trace_sha256=sha(out / "trace.jsonl"), device_answers_sha256=sha(out / "device_answers.jsonl"),
                fairness_digest=meta.get("fairness_digest"), n_dashcam=meta.get("n_dashcam"),
                n_robot=meta.get("n_robot"), n_assistive=meta.get("n_assistive"), wall_s=round(time.time() - t0, 1))


def main() -> None:
    pristine_path, scratch, out_json = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    P = load("trace_pristine", pristine_path)
    N = load("trace_patched", HERE / "fleet" / "trace.py")
    res = dict(pristine=gen(P, scratch / "pristine_40-40-20", "40:40:20"),
               patched=gen(N, scratch / "patched_40-40-20", "40:40:20"),
               committed=dict(trace_sha256=sha(COMMITTED / "trace.jsonl"),
                              device_answers_sha256=sha(COMMITTED / "device_answers.jsonl"),
                              fairness_digest=json.loads((COMMITTED / "trace_meta.json").read_text()).get("fairness_digest")),
               new_keys=[gen(N, scratch / "patched_10-4-2", "10:4:2"), gen(N, scratch / "patched_3-11-2", "3:11:2")],
               ratios_3_pristine=sorted(P.RATIOS_3), ratios_3_patched=sorted(N.RATIOS_3),
               split_identity={r: {n: [list(P._split_fleet3(n, r)), list(N._split_fleet3(n, r))] for n in (4, 8, 12, 16, 20, 24)}
                               for r in ("40:40:20", "50:50:0", "50:50", "75:25", "25:75")})
    p, q, c = res["pristine"], res["patched"], res["committed"]
    keys = ("trace_sha256", "device_answers_sha256", "fairness_digest")
    res["checks"] = dict(
        patched_equals_pristine=all(p[k] == q[k] for k in keys),
        pristine_equals_committed=all(p[k] == c[k] for k in keys),
        split_unchanged_for_existing_ratios=all(a == b for v in res["split_identity"].values() for a, b in v.values()),
        new_key_counts={x["ratio"]: [x["n_dashcam"], x["n_robot"], x["n_assistive"]] for x in res["new_keys"]})
    res["verdict"] = "PASS" if (res["checks"]["patched_equals_pristine"] and res["checks"]["split_unchanged_for_existing_ratios"]
                                and res["checks"]["new_key_counts"] == {"10:4:2": [10, 4, 2], "3:11:2": [3, 11, 2]}) else "FAIL"
    try:
        from _provenance import stamp
        res["_provenance"] = stamp(script="ratios3_identity_proof.py", model="none", device="h100nvl (CPU only)", n=4, args=None)
    except Exception as e:                      # provenance must not mask the proof
        res["_provenance"] = dict(error=repr(e))
    out_json.write_text(json.dumps(res, indent=1, sort_keys=True))
    print(json.dumps(dict(verdict=res["verdict"], checks=res["checks"]), sort_keys=True))


if __name__ == "__main__":
    main()
