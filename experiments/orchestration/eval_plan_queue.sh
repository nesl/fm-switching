#!/bin/bash
# EVAL_PLAN (user, 2026-11-23) queue generator. Writes:
#   runs/FILLER_QUEUE        the D212 filler order plus EVERY evaluation-matrix cell with its status
#                            (done / ready / waiting on <reason>), regenerated from the committed cells
#   runs/MATRIX_READY_CELLS  the matrix cells that are ready and not covered by another gated list, in plan order
# Status rules (research/EVAL_PLAN.md): an arm with an open fidelity hit waits at EVERY condition (its fix changes its
# decision code, so a 1x result is not safe either) until the fix is proven or its card is shown not to read the field;
# a condition whose build is not done waits on that build. Re-run it after any fix, build or cell lands.
set -u
cd /home/pragya/Desktop/fm-switching
O=results/orchestration/live2/frozen_test/runs
ARMS="confidence-cascade covex-v6-base covex-v6-rules simplestream llf mooncake eco-llm"
SEEDS="4 5"
# condition key | n | tag | server flags | build status ("" = ready)
CONDS=$(cat <<'EOF'
mem0.5x|16|_kv0.5r_L3_epg_rq30|--num-gpu-blocks-override 1968 --max-model-len 31472|
mem0.25x|16|_kv0.25_L3_epg_rq30|--num-gpu-blocks-override 985 --max-model-len 15744|
load8|8|_L3_epg_rq30||
load12|12|_L3_epg_rq30||
load20|20|_L3_epg_rq30||
load24|24|_L3_epg_rq30||
dl2.5|16|_L2.5_epg_rq30||
dl4|16|_L4_epg_rq30||
dl5|16|_L5_epg_rq30||
comp10-4-2|16|_c10-4-2_L3_epg_rq30||
comp3-11-2|16|_c3-11-2_L3_epg_rq30||
rq10|16|_L3_epg_rq10||RQV33
rq60|16|_L3_epg_rq60||RQV33
EOF
)
# driver v33 parses _rq<k>; until it is the running driver the re-ask conditions wait
pgrep -u pragya -f "study_frozen_grid_driver_v(3[3-9]|[4-9][0-9]).sh" >/dev/null && RQV33="" || RQV33="waiting on build: driver v33 (_rq<k> tag) running"
armwait() {   # $1 arm, $2 condition key. Open fidelity hits per arm (D209 (2), reduced by the baseline-set ruling)
  # hit 14 card check (2026-11-23 16:50): llf (D118 laxity from committed cost curves) reads NO capacity, so it is
  # unaffected everywhere; mooncake as carded keeps gpu_warm_slots = 4 (StudyE10b), a constant, so it is unaffected at
  # 1x, and whether it should follow the GPU-KV pool at 0.5x / 0.25x is an ADAPTATION change awaiting the user.
  case "$1" in
    simplestream) echo "";;   # hit 7 LANDED c511050; hit 14 card check: no capacity input
    mooncake) echo "";;   # slots sized to the KV pool, landed with its proof (user ruling)
    eco-llm) echo "waiting on hits 14, 16";;
    *) echo "";;
  esac
}
superseded() { grep -qxF "$1" <(printf '%s\n' mooncake_n16_s4_1200s_h27_3t_kv0.25_L3_epg_rq30 simplestream_n16_s4_1200s_h27_3t_kv0.25_L3_epg_rq30 eco-llm_n16_s4_1200s_h27_3t_kv0.25_L3_epg_rq30); }
other_lists() { for f in $(awk '{print $1}' $O/V6_GATE_OK | grep -vx MATRIX_READY_CELLS | sort -u); do grep -v '^#' $O/$f 2>/dev/null | awk 'NF>=4 {print $1, $2, $3, $4}'; done | sort -u; }
OTHER=$(other_lists)
q=$O/FILLER_QUEUE; r=$O/MATRIX_READY_CELLS
{
cat <<'EOF'
# FILLER QUEUE (H100). Generated by experiments/orchestration/eval_plan_queue.sh; plan in research/EVAL_PLAN.md.
# D212: COVEX policy lists (FINAL_LADDER_CELLS and after) are gated ABOVE every filler list and always run first.
# Filler order: a confidence-cascade 1x s4-s7 (_rerun) | b cascade-routing 1x s4-s7 | c fidelity reruns as fixes land
#   (simplestream; llf, mooncake, eco-llm; kvflow-prefetch, lmcache, attentionstore-prefetch) | d covex-v6-base /
#   covex-v6-rules safe subset (D209SAFE_CELLS) then the evaluation matrix (MATRIX_READY_CELLS) | e hybrid-llm (optional, last)
# CANCELLED (outside the paper baseline set): pensieve, rh8, inar-vl, routellm, preble, b9, uniscale; r3-streaming out.
# HELD: 0.25x policy cells, ablations (D210), KV025_RUNGS, the hit-14-affected 0.25x baselines. Held-out seeds 1-3: never.
#
# D212 entries
a  | FILLER_A_CELLS  confidence-cascade 16 s4-s7 _L3_epg_rq30_rerun | ready (gated)
b  | FILLER_C_CELLS  cascade-routing 16 s4-s7 _L3_epg_rq30 | ready (DEVWAIT_READY at 10dae57d). REPORTED, PORT-RULE FAIL: its sufficiency proxy cannot fire here (0 of 489 recall decisions are its skip-or-cascade choice; lambda 0.02 vs 2.0 moves 0), so it sits on the device-only floor by construction (census holds at every seed; s7 recount: 464 recall-path decisions, 446 declines + 18 releases, ZERO the proxy cascade choice; the 18 are RECENT sends of the only over-32k session, robo004 s000, which exists only at s7, D176); its lambda was fitted offline against a cost budget live2 lacks (D58, D174 (1)); never counted as a baseline we beat (D212 (3), D213)
c1 | FILLER_SS_CELLS simplestream 16 s4-s7 _L3_epg_rq30_rerun | ready (hit 7 landed c511050; hit-14 card check: reads no capacity)
c2 | llf: UNAFFECTED by hit 14 (card check); mooncake: unaffected at 1x, memory conditions await the hit-14 adaptation ruling; eco-llm: waiting on hits 14, 16
c3 | kvflow-prefetch, lmcache (hit 9), attentionstore-prefetch (hit 8) reruns | waiting on hits 9, 8
d  | D209SAFE_CELLS covex-v6-base / covex-v6-rules at L2.5, n12, n20 | ready (gated)
e  | FILLER_Z_CELLS  hybrid-llm 16 s4-s7 | optional, last (gated)
#
# EVALUATION MATRIX: condition | arm | n | seed | tag | status
EOF
} > $q
: > $r.tmp
echo "$CONDS" | while IFS='|' read k n tag flags build; do
  [ "$build" = "RQV33" ] && build="$RQV33"
  for s in $SEEDS; do for a in $ARMS; do
    c=${a}_n${n}_s${s}_1200s_h27_3t${tag}
    if [ -f $O/$c/cell.json ]; then
      if superseded $c; then st="SUPERSEDED (hit 14); rerun after the fix"; else st="done"; fi
      w=$(armwait $a $k); [ -n "$w" ] && [ "$st" = done ] && st="done (provisional: $w)"
    else
      w=$(armwait $a $k)
      if [ -n "$w" ]; then st="$w"
      elif [ -n "$build" ]; then st="$build"
      elif echo "$OTHER" | grep -qxF "$a $n $s $tag"; then st="ready (gated in another list)"
      else st="ready (MATRIX_READY_CELLS)"; echo "$a $n $s $tag${flags:+ $flags}" >> $r.tmp; fi
    fi
    echo "$k | $a | $n | $s | $tag | $st" >> $q
  done; done
done
{ echo "# EVAL_PLAN matrix cells that are READY and in no other gated list (generated by eval_plan_queue.sh; plan order)"; cat $r.tmp; } > $r; rm -f $r.tmp
echo "matrix cells: $(grep -cE '^(mem|load|dl|comp|rq)[0-9.x-]* \| ' $q) ; $(grep -E '^(mem|load|dl|comp|rq)[0-9.x-]* \| ' $q | awk -F' \\| ' '{print $6}' | sed -E 's/ \(.*//; s/waiting on build.*/waiting on build/; s/waiting on hit.*/waiting on hits/' | sort | uniq -c | tr -s ' \n' ' ')"
echo "MATRIX_READY_CELLS: $(grep -vc '^#' $r) cells"
